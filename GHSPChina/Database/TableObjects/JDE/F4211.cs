        public static string GetPickManagerFilter(string UserId, string sPickManagerMode, string orderBy, bool includeOrderBy)
        {
            string pickManagerFilter = null;
            switch (sPickManagerMode)
            {
                case "0":
                    pickManagerFilter = "";
                    break;
                case "1":
                    pickManagerFilter = " AND (PMXREFUSID = '" + UserId + "' OR SDURAB = 0)";
                    if (includeOrderBy)
                        pickManagerFilter += " ORDER BY COALESCE(PMXREFUSID, N' ') DESC ";
                    break;
                case "2":
                    pickManagerFilter = " AND PMXREFUSID = '" + UserId + "'";
                    if (includeOrderBy)
                        pickManagerFilter += " ORDER BY COALESCE(PMXREFUSID, N' ') DESC ";
                    break;
                case "3":
                    if (includeOrderBy)
                        pickManagerFilter = " ORDER BY COALESCE(PMXREFUSID, N' ') ";
                    break;
                default:
                    if (includeOrderBy)
                        pickManagerFilter = " ORDER BY COALESCE(PMXREFUSID, N' ') ";
                    break;
            }

            if (!String.IsNullOrWhiteSpace(orderBy))
            {
                if (!pickManagerFilter.Contains("ORDER BY")) //if "ORDER BY" doesn't exist in the string
                {
                    pickManagerFilter += " ORDER BY";
                }
                else //if an order by already started assume it has a column, so add a comma
                {
                    pickManagerFilter += ",";
                }

                pickManagerFilter += String.Format(" {0} ", orderBy);
            }

            return pickManagerFilter;
        }

